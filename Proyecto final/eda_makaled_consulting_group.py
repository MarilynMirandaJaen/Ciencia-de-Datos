d = df_eda.copy()
d["profit_dev"] = d["profit"].where(d["is_returned"] == 1, 0)
d["profit_ok"]  = d["profit"].where(d["is_returned"] == 0, 0)

cli = d.groupby("customer_id").agg(
    ordenes=("order_id", "count"),
    devoluciones=("is_returned", "sum"),
    profit_dev=("profit_dev", "sum"),
    profit_ok=("profit_ok", "sum"),
)
cli["impacto"] = cli["profit_ok"] - cli["profit_dev"]

print(cli["devoluciones"].value_counts().sort_index())
print(f"\nClientes con impacto negativo: {(cli['impacto'] < 0).sum():,}")

CORTE_FREC = 2   # devoluciones mínimas para considerar "recurrente"

def zona(r):
    if r["devoluciones"] == 0:
        return "Sin devoluciones"
    if r["impacto"] >= 0:
        return "Insatisfecho"
    return "Tóxico" if r["devoluciones"] >= CORTE_FREC else "Pérdida puntual"

cli["zona"] = cli.apply(zona, axis=1)

colores = {"Insatisfecho": "#f4a261", "Pérdida puntual": "#e9c46a", "Tóxico": "#c1121f"}
dev = cli[cli["devoluciones"] > 0].copy()
